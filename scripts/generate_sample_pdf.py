from pathlib import Path

import fitz


def make_sample_pdf(path: str, pages: int = 3) -> Path:
    """Create a small multi-page PDF used by the examples/tests.

    - Page 1: simple title + paragraph
    - Page 2: includes a small table-like block (for pdfplumber demo)
    - Page 3: footer text
    Returns the Path to the written file.
    """
    path = Path(path)
    doc = fitz.open()

    for p in range(1, pages + 1):
        page = doc.new_page()
        title = f"Sample PDF — page {p}"
        page.insert_text((72, 72), title, fontsize=18)

        if p == 1:
            page.insert_text(
                (72, 110),
                "This PDF is generated by scripts/generate_sample_pdf.py for examples and tests.",
                fontsize=12,
            )
        elif p == 2:
            # table text + drawn grid so pdfplumber can detect a table
            table_lines = [
                "Table Header",
                "Col1    Col2    Col3",
                "row1    100     abc",
                "row2    200     def",
            ]
            y0 = 110
            x0 = 72
            line_height = 14
            for i, line in enumerate(table_lines):
                page.insert_text((x0, y0 + i * line_height), line, fontsize=11, fontname="courier")

            # draw a simple grid around the table (3 columns x 4 rows)
            cols = [x0, x0 + 90, x0 + 180, x0 + 270]
            top = y0 - 8
            bottom = y0 + line_height * len(table_lines) + 4

            # horizontal lines (top + between rows + bottom)
            for r in range(len(table_lines) + 1):
                ry = top + r * line_height
                page.draw_line((cols[0], ry), (cols[-1], ry), color=(0, 0, 0), width=0.8)

            # vertical column lines
            for cx in cols:
                page.draw_line((cx, top), (cx, bottom), color=(0, 0, 0), width=0.8)
        else:
            page.insert_text((72, 110), "End of sample PDF.", fontsize=12)

    path.parent.mkdir(parents=True, exist_ok=True)
    doc.save(str(path))
    doc.close()
    return path


if __name__ == "__main__":
    # default to examples/ so the sample is kept with example code
    out = make_sample_pdf("examples/sample_example.pdf")
    print("Wrote:", out)
